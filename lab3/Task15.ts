// Task 15: Необязательные свойства объектов
// Использование опциональных свойств (?) в типах объектов
namespace Task15
{
    // Объект, где age — необязательное свойство
    let user: {
        name: string,      // имя обязательно
        age?: number,      // возраст необязателен
    };
    // Валидно: только обязательное свойство
    user = {name: 'John'};
    // Валидно: оба свойства
    user = {name: 'John', age: 30};

    // Объект, где day — необязательное свойство
    let date:
    {
        year: number,      // год обязательно
        month: number,     // месяц обязательно
        day?: number,      // день необязателен
    };
    // Валидно: без day
    date = {
        year: 2025,
        month: 12,
    };
    console.log(date); // { year: 2025, month: 12 }
}