// Task 1: Define an enum for weekdays
// Task 1: Перечисление дней недели
// Enum (перечисление) — это способ задать набор именованных констант
enum weekDays 
{
    Monday = 1,      // Понедельник — 1
    Tuesday = 2,     // Вторник — 2
    Wednesday = 3,   // Среда — 3
    Thursday = 4,    // Четверг — 4
    Friday = 5,      // Пятница — 5
    Suturday = 6,    // Суббота — 6 (опечатка: должно быть Saturday)
    Sunday = 7       // Воскресенье — 7
}
